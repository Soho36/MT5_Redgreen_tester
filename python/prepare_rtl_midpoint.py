"""Prepare native midpoint-entry RTL, an unchanged control and stop-only sensitivity."""
import hashlib
import json
import re
import shutil
from project_paths import PROJECT_ROOT as ROOT

BASE = ROOT / 'Reports/timeframe_baseline_20261015'
RUN = ROOT / 'Reports/rtl_midpoint_20261116'
DOC = ROOT / 'docs/baseline/rtl-midpoint'
EXPERT = 'RTL_midpoint'
SOURCE = ROOT / 'mt5/experts/RTL_midpoint.mq5'
ARMS = {'baseline': False, 'stop_only': True}

def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()

def tag(arm):
    return 'midpoint_20261116_' + arm

def build_source():
    s = (BASE / 'RTL_timeframe.mq5').read_text(encoding='utf-8')
    assert sha(BASE / 'RTL_timeframe.mq5') == '8995d0ed6f97f21b15f4ce31f862fb8f642a1eae5a4e28c6bc371cb928165810'
    edits = [
        ('input double RiskReward     = 1.0;',
         'input double RiskReward     = 1.0;\ninput bool UseMidpoint = true;'),
        ('int OnInit()\n{', 'int OnInit()\n{\n   if(!MQLInfoInteger(MQL_TESTER)) return INIT_FAILED; // research only'),
        ('double entry = h1;', '''double entry = h1;
       if(UseMidpoint)
       {
          double tick = SymbolInfoDouble(_Symbol, SYMBOL_TRADE_TICK_SIZE);
          if(tick <= 0.0) tick = _Point;
          entry = NormalizeDouble(MathCeil((h1 + l1) / (2.0 * tick) - 1e-9) * tick, _Digits);
          double ask = SymbolInfoDouble(_Symbol, SYMBOL_ASK);
          if(entry <= ask) return;
       }'''),
    ]
    for old, new in edits:
        assert s.count(old) == 1, repr(old)
        s = s.replace(old, new)
    return '// RTL midpoint research. Generated by python/prepare_rtl_midpoint.py.\n' + s

def main():
    assert (DOC / 'PROTOCOL.md').exists()
    assert not (RUN / 'manifest.json').exists(), 'Preserve prepared study'
    RUN.mkdir(parents=True, exist_ok=True)
    s = build_source()
    SOURCE.write_text(s, encoding='utf-8')
    (RUN / (EXPERT + '.mq5')).write_text(s, encoding='utf-8')
    shutil.copyfile(BASE / 'early_closes.mqh', RUN / 'early_closes.mqh')
    jobs = []
    declared = set(re.findall(r'^input\s+\w+\s+(\w+)\s*=', s, re.M))
    for arm, mid in ARMS.items():
        lines = (BASE / 'tf_20261015_rtl_m30_rr1p0.ini').read_text(encoding='utf-16').splitlines()
        changes = {'Expert': f'CodexResearch\\{EXPERT}.ex5', 'RunTag': tag(arm), 'Report': tag(arm) + '.htm'}
        for key, value in changes.items():
            assert sum(x.startswith(key + '=') for x in lines) == 1
            lines = [key + '=' + value if x.startswith(key + '=') else x for x in lines]
        idx = lines.index('[TesterInputs]') + 1
        lines[idx:idx] = [f'UseMidpoint={str(mid).lower()}']
        settings = {line.split('=')[0] for line in lines[idx:lines.index('[Experts]')] if '=' in line}
        assert declared == settings, declared ^ settings
        (RUN / (tag(arm) + '.ini')).write_text('\n'.join(lines) + '\n', encoding='utf-16')
        jobs.append(dict(tag=tag(arm), arm=arm, outputs=[f'runband_{tag(arm)}_1.00.csv', f'runband_{tag(arm)}_1.00_stats.csv']))
    files = [DOC / 'PROTOCOL.md', BASE / 'RTL_timeframe.mq5', BASE / 'tf_20261015_rtl_m30_rr1p0.ini',
             ROOT / 'python/prepare_rtl_midpoint.py', SOURCE, *RUN.glob('*.mq5'), *RUN.glob('*.mqh'), *RUN.glob('*.ini')]
    manifest = dict(expert=EXPERT, jobs=jobs, input_hashes={str(p): sha(p) for p in files})
    (RUN / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    print('Prepared', RUN)

if __name__ == '__main__':
    main()
