{
   CLOCK_AUTO    = 0,  // Auto: custom symbol = session clock, broker symbol = UTC
   CLOCK_SESSION = 1,  // Session clock (Chicago + 8 h, research symbols)
   CLOCK_UTC     = 2   // UTC (AMP live symbols, e.g. MNQZ26)
};
