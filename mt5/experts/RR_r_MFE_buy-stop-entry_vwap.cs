// ======== EA CORE ========
int OnInit()
{
   if(TrailDistanceR < 0.0 || TrailStartR <= 0.0)
   {
      Print("Invalid trailing inputs: TrailStartR must be > 0, TrailDistanceR >= 0");
      return INIT_PARAMETERS_INCORRECT;
   }

   if(SnapshotBars < 0)
   {
      Print("SnapshotBars must be >= 0");
      return INIT_PARAMETERS_INCORRECT;
   }
   if(!MathIsValidNumber(MinLocation) || MinLocation < 0.0 || MinLocation > 1.0
      || LocationLookback < 1)
   {
      Print("Invalid location inputs: MinLocation must be in [0,1], LocationLookback >= 1");
      return INIT_PARAMETERS_INCORRECT;
   }

   g_utcServer = (ServerClock == CLOCK_UTC
                  || (ServerClock == CLOCK_AUTO && !SymbolInfoInteger(_Symbol, SYMBOL_CUSTOM)));

   if(_Period != PERIOD_M30 && (UseVwapGate || LogVwapDecisions))
   {
      Print("The VWAP gate is defined on M30 signal bars; attach to an M30 chart");
      return INIT_PARAMETERS_INCORRECT;
   }
   if(!MathIsValidNumber(VwapFarBelowZ) || VwapAnchorMinute < 0 || VwapAnchorMinute >= 1440 || NotionalPerTrade < 0.0)
   {
      Print("Invalid VWAP/sizing inputs");
      return INIT_PARAMETERS_INCORRECT;
   }
   if(VwapLabelFile != "" && (UseVwapGate || LogVwapDecisions))
   {
      if(g_utcServer)
      {
         Print("VwapLabelFile needs a symbol whose server time is the session clock (research or stock custom symbols)");
         return INIT_PARAMETERS_INCORRECT;
      }
      if(!RtlVwapFileLoad(VwapLabelFile)) return INIT_FAILED;
      Print("VWAP labels: ", g_rvCount, " M30 bars from ", VwapLabelFile, " (", TimeToString(g_rvBar[0], TIME_DATE), " to ",
            TimeToString(g_rvBar[g_rvCount - 1], TIME_DATE), ")");
   }
   else if((UseVwapGate || LogVwapDecisions) && MQLInfoInteger(MQL_TESTER))
      Print("WARNING: VWAP computed in the Strategy Tester uses the tester's synthetic 1-minute volume, not the real one. ",
            "For history tests set VwapLabelFile.");
   // Name the export per window+RiskReward so passes never overwrite each other.
   // Empty RunTag => label derived from the enabled window(s).
   g_runTag  = (RunTag == "" ? ActiveWindowLabel() : RunTag);
   g_csvName = "rtlvwap_" + g_runTag + "_" + DoubleToString(RiskReward, 2) + ".csv";
   Print("Run tag: ", g_runTag, "   ->   ", g_csvName);

   // Delete previous stats file if exists
   if(FileIsExist(g_csvName, FILE_COMMON))
   {
      if(FileDelete(g_csvName, FILE_COMMON))
         Print("Old trade_stats.csv deleted");
      else
         Print("Failed to delete old CSV. Error=", GetLastError());
   }

   if(LogVwapDecisions)
   {
      g_vwapLog = FileOpen("vwap_decisions_" + g_runTag + ".csv", FILE_WRITE|FILE_CSV|FILE_ANSI|FILE_COMMON, '\t');
      if(g_vwapLog == INVALID_HANDLE) { Print("Cannot open the VWAP decision log"); return INIT_FAILED; }
      FileWrite(g_vwapLog, "time", "signal_bar", "signal_close", "vwap", "a20", "z", "known", "blocked");
   }

   DisplaySettings();
   Print("VWAP gate: ", UseVwapGate ? "ON (z < " + DoubleToString(VwapFarBelowZ, 2)
         + (VwapLabelFile != "" ? ", labels from " + VwapLabelFile : ", computed, anchor minute " + (string)VwapAnchorMinute)
         + ")" : "OFF", ", early-close set: ",
         EarlyCloseSet == EARLY_CLOSE_US_STOCKS ? "US stocks" : "CME",
         ", sizing: ", NotionalPerTrade > 0.0 ? DoubleToString(NotionalPerTrade, 2) + " per trade" : DoubleToString(Lots, 2) + " lots");
   return(INIT_SUCCEEDED);
}

