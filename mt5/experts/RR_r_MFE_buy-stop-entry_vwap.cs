// Tick-level trailing stop for the open long position (see TrailDistanceR).
void UpdateTrailingStop()
{
   if(TrailDistanceR <= 0.0 || !g_initialSet || g_initialRisk <= 0.0) return;
   if(!PositionSelect(_Symbol)) return;

   double bid = SymbolInfoDouble(_Symbol, SYMBOL_BID);
   g_trailHigh = MathMax(g_trailHigh, bid);
   if(g_trailHigh < g_initialEntry + TrailStartR * g_initialRisk) return;

   double tick = SymbolInfoDouble(_Symbol, SYMBOL_TRADE_TICK_SIZE);
   if(tick <= 0.0) tick = _Point;
   double newSl = MathFloor((g_trailHigh - TrailDistanceR * g_initialRisk) / tick) * tick;
   newSl = NormalizeDouble(newSl, _Digits);

   double curSl  = PositionGetDouble(POSITION_SL);
   double minGap = SymbolInfoInteger(_Symbol, SYMBOL_TRADE_STOPS_LEVEL) * _Point;
   if(newSl < curSl + tick || newSl > bid - minGap - tick) return;

   MqlTradeRequest req = {};
   MqlTradeResult  res = {};
   req.action   = TRADE_ACTION_SLTP;
   req.symbol   = _Symbol;
   req.position = PositionGetInteger(POSITION_TICKET);
   req.sl       = newSl;
   req.tp       = PositionGetDouble(POSITION_TP);
   if(!OrderSend(req, res))
      Print("Trailing SL modify failed err=", GetLastError(), " retcode=", res.retcode, " sl=", newSl);
}

// Flatten cutoff for this bar's date, in minutes after midnight.
int FlattenCutoffMinutes(datetime barOpen)
{
   MqlDateTime dt; TimeToStruct(barOpen, dt);
   if(UseEarlyCloseCalendar)
   {
      int key = dt.year * 10000 + dt.mon * 100 + dt.day;
      bool stocks = (EarlyCloseSet == EARLY_CLOSE_US_STOCKS);
      int lo = 0, hi = (stocks ? SEC_COUNT : EC_COUNT) - 1;
      while(lo <= hi)
      {
         int mid = (lo + hi) / 2;
         int date = stocks ? SEC_DATE[mid] : EC_DATE[mid];
         if(date == key) return stocks ? SEC_FLAT_MIN[mid] : EC_FLAT_MIN[mid];
         if(date < key) lo = mid + 1; else hi = mid - 1;
      }
   }
   return FlattenHourEnd * 60 + FlattenMinuteEnd;
}

// ======== SESSION VWAP GATE ========
int g_vwapLog = INVALID_HANDLE;
int g_vwapCandidates = 0, g_vwapKnown = 0, g_vwapBlocked = 0;

// True when the new buy stop may be placed. Signal bar = the last completed M30 bar.
bool VwapGateAllows(datetime barOpen, double close1)
{
   if(!UseVwapGate && !LogVwapDecisions) return true;
   datetime signalBar = iTime(_Symbol, _Period, 1);
   int shift = (int)(SessionClock(signalBar) - signalBar);
   datetime nowClock = SessionClock(barOpen), sigClock = signalBar + shift;
   bool sameSession = (nowClock - nowClock % 86400) == (sigClock - sigClock % 86400);
   double vwap = 0.0, a20 = 0.0;
   bool known = false;
   if(VwapLabelFile != "")
   {
      // The replay's lookup: newest label available now, known only for today's session.
      datetime now = TimeCurrent(), date = now - now % 86400;
      int j = RtlVwapFileRow(now);
      known = (j >= 0 && g_rvKnown[j] && g_rvSession[j] == date);
      if(known && (g_rvBar[j] != signalBar || MathAbs(g_rvClose[j] - close1) > _Point))
      {
         Print("VWAP label file does not match this chart at ", TimeToString(signalBar), ": file bar ",
               TimeToString(g_rvBar[j]), " close ", DoubleToString(g_rvClose[j], _Digits), " - stopping");
         ExpertRemove();
         return false;
      }
      if(known) { vwap = g_rvVwap[j]; a20 = g_rvA20[j]; }
   }
   else
      known = sameSession && RtlSessionVwap(_Symbol, signalBar, shift, VwapAnchorMinute, VwapVolume, vwap)
              && RtlA20(_Symbol, 1, a20);
   double z = known ? (close1 - vwap) / a20 : 0.0;
   // close < VWAP + Z x A20 is z < Z without the division; at Z = -1 it is the study's close < VWAP - A20.
   bool blocked = UseVwapGate && known && close1 < vwap + VwapFarBelowZ * a20;
   g_vwapCandidates++;
   if(known)   g_vwapKnown++;
   if(blocked) g_vwapBlocked++;
   if(g_vwapLog != INVALID_HANDLE)
      FileWrite(g_vwapLog, TimeToString(barOpen, TIME_DATE|TIME_SECONDS), TimeToString(signalBar, TIME_DATE|TIME_SECONDS),
                DoubleToString(close1, _Digits), known ? DoubleToString(vwap, 10) : "", known ? DoubleToString(a20, 10) : "",
                known ? DoubleToString(z, 10) : "", (int)known, (int)blocked);
   if(blocked)
      Print("⛔ VWAP gate: close ", DoubleToString(close1, _Digits), " < VWAP ", DoubleToString(vwap, _Digits),
            " - A20 ", DoubleToString(a20, _Digits), " (z=", DoubleToString(z, 2), ") - no new buy stop");
   return !blocked;
}

double OrderVolume(double entry)
{
   if(NotionalPerTrade <= 0.0) return Lots;
   double step = SymbolInfoDouble(_Symbol, SYMBOL_VOLUME_STEP);
   double vmin = SymbolInfoDouble(_Symbol, SYMBOL_VOLUME_MIN), vmax = SymbolInfoDouble(_Symbol, SYMBOL_VOLUME_MAX);
   if(step <= 0.0 || entry <= 0.0) return Lots;
   double volume = MathFloor(NotionalPerTrade / entry / step + 1e-9) * step;
   int digits = (int)MathMax(0, MathCeil(-MathLog10(step) - 1e-9));
   return NormalizeDouble(MathMax(vmin, MathMin(vmax, volume)), digits);
}

