//+------------------------------------------------------------------+
//| RTL mirrored: SELL LIMIT at the high of the last red candle       |
//| Research EA, Strategy Tester only.                                |
//|                                                                   |
//| RTL buys a break of the red candle's high: buy stop at the high,  |
//| stop at the low, close after a bar closes at +1R or better.       |
//| This EA takes the other side at the same price:                   |
//|   entry   sell limit at the red high (+ EntryOffsetTicks)         |
//|   stop    entry + the candle's range (one range above the high)   |
//|   target  entry - RiskReward x range (RiskReward 1 = the red low) |
//| ExitMode 0 (default, RTL's exit mirrored): buy back at the first  |
//|   quote of the next bar after a bar CLOSES at or below the target,|
//|   so the profit is the target at least.                           |
//| ExitMode 1: a resting take profit at the target instead.          |
//|                                                                   |
//| Order lifetime, entry windows, the 23:30 flatten, its fallback    |
//| and the early-close calendar are those of                         |
//| RR_r_MFE_buy-stop-entry_runband. One position at a time.          |
//| No order when the new bar opens at or above the red high (MT5     |
//| rejects RTL's buy stop there); see AllowOrderAtMarket.            |
//| Unlike that EA, the trade windows default to RTL's 01:00-23:30,   |
//| so a run with default inputs trades.                              |
//| Protocol: docs/baseline/rtl-sell-limit-fade/PROTOCOL.md           |
//+------------------------------------------------------------------+
#property strict

#include "early_closes.mqh"   // EC_DATE / EC_FLAT_MIN, generated by python/build_early_close_calendar.py

input double Lots             = 1.0;
input double RiskReward       = 1.0;  // Target distance in candle ranges (1 = the red low)
input int    Slippage         = 5;
input int    EntryOffsetTicks = 0;    // Sell limit this many ticks above the red high (0 = at the high)
// A new bar can open at or above the red high, so the level is no longer above
// the market. MT5 rejects RTL's buy stop there, but it accepts a sell limit and
// fills it at once at the market price. false (default): no order, the same
// signals as RTL. true: send the order anyway.
input bool   AllowOrderAtMarket = false;

enum EXIT_MODE
{
   EXIT_BAR_CLOSE  = 0,  // After a bar closes at/below the target (RTL's exit, mirrored)
   EXIT_RESTING_TP = 1   // Resting take profit at the target
};
input EXIT_MODE ExitMode = EXIT_BAR_CLOSE;

// ======== SESSION FLATTEN (as in the RTL EA) ========
input bool   UseFlattenEnd     = true;  // USE FLATTENING END SESSION
input int    FlattenHourEnd    = 23;
input int    FlattenMinuteEnd  = 30;
// Flatten at the first bar AT OR AFTER the cutoff; if a date ends without a
// flatten, flatten on the first bar of the next date.
input bool   FlattenFallback   = true;
// Early-closing sessions flatten at the open of their last M30 bar.
input bool   UseEarlyCloseCalendar = true;

// ======== SERVER CLOCK (as in the RTL EA) ========
// Time-of-day inputs are on the session clock (Chicago + 8 h). Research symbols
// already use it; a broker symbol on UTC is shifted +2 h / +3 h (US DST).
enum SERVER_CLOCK
{
   CLOCK_AUTO    = 0,  // Auto: custom symbol = session clock, broker symbol = UTC
   CLOCK_SESSION = 1,  // Session clock (Chicago + 8 h, research symbols)
   CLOCK_UTC     = 2   // UTC (AMP live symbols, e.g. MNQZ26)
};
input SERVER_CLOCK ServerClock = CLOCK_AUTO;

// ======== ENTRY WINDOWS (true = new orders allowed) ========
input bool   UseTradeWindow = true;   // USE TIME TRADE WINDOW
input string RunTag = "";             // filename tag for the CSV exports ("" = "run")

input bool W0000W0100 = false;  // 00:00-01:00 (Market Closed)
input bool W0100W0130 = true;   // 01:00-01:30
input bool W0130W0200 = true;   // 01:30-02:00
input bool W0200W0300 = true;   // 02:00-03:00
input bool W0300W0400 = true;   // 03:00-04:00
input bool W0400W0500 = true;   // 04:00-05:00
input bool W0500W0600 = true;   // 05:00-06:00
input bool W0600W0700 = true;   // 06:00-07:00
input bool W0700W0800 = true;   // 07:00-08:00
input bool W0800W0900 = true;   // 08:00-09:00
input bool W0900W1000 = true;   // 09:00-10:00
input bool W1000W1100 = true;   // 10:00-11:00
input bool W1100W1200 = true;   // 11:00-12:00
input bool W1200W1300 = true;   // 12:00-13:00
input bool W1300W1400 = true;   // 13:00-14:00
input bool W1400W1500 = true;   // 14:00-15:00
input bool W1500W1600 = true;   // 15:00-16:00
input bool W1600W1700 = true;   // 16:00-17:00
input bool W1700W1800 = true;   // 17:00-18:00
input bool W1800W1900 = true;   // 18:00-19:00
input bool W1900W2000 = true;   // 19:00-20:00
input bool W2000W2100 = true;   // 20:00-21:00
input bool W2100W2200 = true;   // 21:00-22:00
input bool W2200W2300 = true;   // 22:00-23:00
input bool W2300W2330 = true;   // 23:00-23:30
input bool W2330W0000 = false;  // 23:30-00:00

bool windows[26] =
{
   W0000W0100,
   W0100W0130, W0130W0200,
   W0200W0300, W0300W0400, W0400W0500, W0500W0600,
   W0600W0700, W0700W0800, W0800W0900, W0900W1000,
   W1000W1100, W1100W1200, W1200W1300, W1300W1400,
   W1400W1500, W1500W1600, W1600W1700, W1700W1800,
   W1800W1900, W1900W2000, W2000W2100, W2100W2200,
   W2200W2300,
   W2300W2330, W2330W0000
};

// ======== STATE ========
bool   g_wasInPosition = false;
double g_initialEntry  = 0.0;   // fill price of the open short
double g_initialRisk   = 0.0;   // its stop distance (stop - entry)
bool   g_initialSet    = false;

double   g_maeMoney    = 0.0;   // most negative floating PnL
double   g_mfeMoney    = 0.0;   // most positive floating PnL
bool     g_tracking    = false;
ulong    g_ticket      = 0;
datetime g_entryTime   = 0;
double   g_candleRange = 0.0;   // range of the signal candle behind the resting order

datetime g_prevBarDate     = 0; // date (00:00) of the previous new bar
datetime g_lastFlattenDate = 0; // date on which the last session flatten ran

string g_runTag    = "";
string g_csvName   = "";
bool   g_utcServer = false;
int    g_placed = 0, g_rejected = 0, g_skipped = 0;   // g_skipped: level not above the market

// ======== SESSION CLOCK AND WINDOWS ========

// Date of the n-th Sunday of a month, 00:00.
datetime NthSunday(int year, int month, int n)
{
   MqlDateTime d = {};
   d.year = year; d.mon = month; d.day = 1;
   datetime first = StructToTime(d);
   TimeToStruct(first, d);
   return first + ((7 - d.day_of_week) % 7 + 7 * (n - 1)) * 86400;
}

// Server time -> session clock. Chicago + 8 h is UTC + 3 h from the second
// Sunday of March 08:00 UTC to the first Sunday of November 07:00 UTC, else UTC + 2 h.
datetime SessionClock(datetime server)
{
   if(!g_utcServer) return server;
   MqlDateTime dt; TimeToStruct(server, dt);
   datetime dstStart = NthSunday(dt.year, 3, 2) + 8 * 3600;
   datetime dstEnd   = NthSunday(dt.year, 11, 1) + 7 * 3600;
   return server + ((server >= dstStart && server < dstEnd) ? 3 : 2) * 3600;
}

bool IsFlattenTimeEnd(datetime barOpen)
{
   MqlDateTime dt; TimeToStruct(barOpen, dt);
   return (dt.hour == FlattenHourEnd && dt.min == FlattenMinuteEnd);
}

// Flatten cutoff for this bar's date, in minutes after midnight.
int FlattenCutoffMinutes(datetime barOpen)
{
   MqlDateTime dt; TimeToStruct(barOpen, dt);
   if(UseEarlyCloseCalendar)
   {
      int key = dt.year * 10000 + dt.mon * 100 + dt.day;
      int lo = 0, hi = EC_COUNT - 1;
      while(lo <= hi)
      {
         int mid = (lo + hi) / 2;
         if(EC_DATE[mid] == key) return EC_FLAT_MIN[mid];
         if(EC_DATE[mid] < key) lo = mid + 1; else hi = mid - 1;
      }
   }
   return FlattenHourEnd * 60 + FlattenMinuteEnd;
}

bool IsAtOrAfterFlattenTime(datetime barOpen)
{
   MqlDateTime dt; TimeToStruct(barOpen, dt);
   return (dt.hour * 60 + dt.min >= FlattenCutoffMinutes(barOpen));
}

bool IsTradeWindow(datetime barOpen)
{
   if(!UseTradeWindow) return true;

   MqlDateTime dt; TimeToStruct(barOpen, dt);
   int totalMinutes = dt.hour * 60 + dt.min;
   int slot;
   if(totalMinutes < 60)        slot = 0;                               // 00:00-01:00
   else if(totalMinutes < 120)  slot = 1 + ((totalMinutes - 60) / 30);  // 01:00-02:00, half hours
   else if(totalMinutes < 1380) slot = 3 + (dt.hour - 2);               // 02:00-23:00, hours
   else                         slot = 24 + ((totalMinutes - 1380) / 30); // 23:00-00:00, half hours
   return windows[slot];
}

// ======== CSV EXPORT ========
void SaveTradeStats(double realized, datetime entryTime, datetime exitTime)
{
   int f = FileOpen(g_csvName, FILE_READ|FILE_WRITE|FILE_CSV|FILE_SHARE_WRITE|FILE_COMMON);
   if(f == INVALID_HANDLE)
   {
      Print("File open failed ", GetLastError());
      return;
   }
   // A new Unicode CSV may already contain its two-byte BOM.
   if(FileSize(f) <= 2)
      FileWrite(f, "ticket", "entry_time", "exit_time", "mae_money", "mfe_money", "trade_profit", "candle_range");
   FileSeek(f, 0, SEEK_END);
   FileWrite(f, (long)g_ticket,
             TimeToString(entryTime, TIME_DATE|TIME_SECONDS),
             TimeToString(exitTime, TIME_DATE|TIME_SECONDS),
             g_maeMoney, g_mfeMoney, realized, g_candleRange);
   FileClose(f);
}

// Flush a tracked close, including a tester-forced close after the last tick.
void SaveClosedTrackedTrade()
{
   if(!g_tracking || PositionSelect(_Symbol)) return;
   if(!HistorySelect(g_entryTime - 86400, TimeCurrent())) return;

   double realized = 0.0;
   datetime exitTime = 0;
   for(int i = HistoryDealsTotal() - 1; i >= 0; i--)
   {
      ulong deal = HistoryDealGetTicket(i);
      if(HistoryDealGetInteger(deal, DEAL_POSITION_ID) != g_ticket) continue;
      realized += HistoryDealGetDouble(deal, DEAL_PROFIT);
      if(HistoryDealGetInteger(deal, DEAL_ENTRY) == DEAL_ENTRY_OUT)
      {
         exitTime = (datetime)HistoryDealGetInteger(deal, DEAL_TIME);
         break;
      }
   }
   if(exitTime == 0) return;
   g_maeMoney = MathMin(g_maeMoney, realized);
   g_mfeMoney = MathMax(g_mfeMoney, realized);
   SaveTradeStats(realized, g_entryTime, exitTime);
   g_tracking = false;
}

// ======== ORDERS AND POSITIONS ========
void CancelAllOrders()
{
   for(int i = OrdersTotal() - 1; i >= 0; --i)
   {
      ulong ticket = OrderGetTicket(i);
      if(ticket == 0 || !OrderSelect(ticket)) continue;

      MqlTradeRequest req = {};
      MqlTradeResult  res = {};
      req.action = TRADE_ACTION_REMOVE;
      req.order  = ticket;
      if(!OrderSend(req, res))
         Print("CancelAllOrders failed ticket=", ticket, " err=", GetLastError());
   }
}

void CancelOldSellLimits()
{
   for(int i = OrdersTotal() - 1; i >= 0; --i)
   {
      ulong ticket = OrderGetTicket(i);
      if(ticket == 0 || !OrderSelect(ticket)) continue;
      if((int)OrderGetInteger(ORDER_TYPE) != ORDER_TYPE_SELL_LIMIT) continue;

      MqlTradeRequest req = {};
      MqlTradeResult  res = {};
      req.action = TRADE_ACTION_REMOVE;
      req.order  = ticket;
      if(!OrderSend(req, res))
         Print("Cancel Sell Limit failed ticket=", ticket, " err=", GetLastError());
   }
}

void CloseAllPositions()
{
   for(int i = PositionsTotal() - 1; i >= 0; --i)
   {
      ulong ticket = PositionGetTicket(i);
      if(ticket == 0 || !PositionSelectByTicket(ticket)) continue;

      string sym = PositionGetString(POSITION_SYMBOL);
      bool   buy = (PositionGetInteger(POSITION_TYPE) == POSITION_TYPE_BUY);

      MqlTradeRequest req = {};
      MqlTradeResult  res = {};
      req.action    = TRADE_ACTION_DEAL;
      req.symbol    = sym;
      req.volume    = PositionGetDouble(POSITION_VOLUME);
      req.deviation = Slippage;
      req.type      = buy ? ORDER_TYPE_SELL : ORDER_TYPE_BUY;
      req.price     = SymbolInfoDouble(sym, buy ? SYMBOL_BID : SYMBOL_ASK);
      if(!OrderSend(req, res))
         Print("CloseAllPositions failed pos#", ticket, " err=", GetLastError());
   }
}

// RTL's bar-close exit, mirrored: after a bar closes at or below the target,
// buy the short back at market. With a resting take profit there is nothing to do.
void ManageOpenPosition()
{
   if(ExitMode != EXIT_BAR_CLOSE) return;
   if(!PositionSelect(_Symbol)) return;
   if(PositionGetInteger(POSITION_TYPE) != POSITION_TYPE_SELL) return;
   if(!g_initialSet || g_initialRisk <= 0.0)
   {
      Print("Initial reference not set -> skipping target check");
      return;
   }

   double target = g_initialEntry - g_initialRisk * RiskReward;
   if(iClose(_Symbol, _Period, 1) > target) return;

   MqlTradeRequest req = {};
   MqlTradeResult  res = {};
   req.action    = TRADE_ACTION_DEAL;
   req.symbol    = _Symbol;
   req.volume    = PositionGetDouble(POSITION_VOLUME);
   req.type      = ORDER_TYPE_BUY;
   req.price     = SymbolInfoDouble(_Symbol, SYMBOL_ASK);
   req.deviation = Slippage;
   if(!OrderSend(req, res))
      Print("Target close failed err=", GetLastError(), " retcode=", res.retcode);
}

// ======== EA CORE ========
int OnInit()
{
   if(!MQLInfoInteger(MQL_TESTER))
   {
      Print("RTL_red_high_sell_limit is a research EA: Strategy Tester only.");
      return INIT_FAILED;
   }
   if(Lots <= 0.0 || RiskReward <= 0.0 || EntryOffsetTicks < 0)
   {
      Print("Invalid inputs: Lots and RiskReward must be > 0, EntryOffsetTicks >= 0");
      return INIT_PARAMETERS_INCORRECT;
   }

   g_utcServer = (ServerClock == CLOCK_UTC
                  || (ServerClock == CLOCK_AUTO && !SymbolInfoInteger(_Symbol, SYMBOL_CUSTOM)));

   g_runTag  = (RunTag == "" ? "run" : RunTag);
   g_csvName = "sell_limit_" + g_runTag + "_" + DoubleToString(RiskReward, 2) + ".csv";
   if(FileIsExist(g_csvName, FILE_COMMON))
      FileDelete(g_csvName, FILE_COMMON);

   Print("RTL mirrored sell limit: Lots=", Lots, " RiskReward=", RiskReward,
         " EntryOffsetTicks=", EntryOffsetTicks, " AllowOrderAtMarket=", AllowOrderAtMarket,
         " Exit=", (ExitMode == EXIT_BAR_CLOSE ? "bar close at/below target" : "resting take profit"),
         " -> ", g_csvName);
   return INIT_SUCCEEDED;
}

// MT5's own figures for this pass, next to the per-trade export.
double OnTester()
{
   SaveClosedTrackedTrade();
   string fn = "sell_limit_" + g_runTag + "_" + DoubleToString(RiskReward, 2) + "_stats.csv";
   int f = FileOpen(fn, FILE_WRITE|FILE_CSV|FILE_COMMON);
   if(f == INVALID_HANDLE)
   {
      Print("Stats file open failed ", GetLastError());
      return 0.0;
   }
   FileWrite(f, "run_tag", "risk_reward", "exit_mode", "entry_offset_ticks", "allow_order_at_market",
                "orders_placed", "orders_rejected", "orders_skipped_at_market",
                "trades", "net_profit", "gross_profit", "gross_loss", "equity_dd", "balance_dd",
                "profit_factor", "expected_payoff");
   FileWrite(f, g_runTag, RiskReward, (int)ExitMode, EntryOffsetTicks, (int)AllowOrderAtMarket,
                g_placed, g_rejected, g_skipped,
                (int)TesterStatistics(STAT_TRADES),
                TesterStatistics(STAT_PROFIT),
                TesterStatistics(STAT_GROSS_PROFIT),
                TesterStatistics(STAT_GROSS_LOSS),
                TesterStatistics(STAT_EQUITY_DD),
                TesterStatistics(STAT_BALANCE_DD),
                TesterStatistics(STAT_PROFIT_FACTOR),
                TesterStatistics(STAT_EXPECTED_PAYOFF));
   FileClose(f);
   return 0.0;
}

void OnTick()
{
   // ---- floating MAE / MFE of the open trade
   if(PositionSelect(_Symbol))
   {
      double floating = PositionGetDouble(POSITION_PROFIT);
      if(!g_tracking)
      {
         g_tracking  = true;
         g_ticket    = PositionGetInteger(POSITION_TICKET);
         g_entryTime = (datetime)PositionGetInteger(POSITION_TIME);
         g_maeMoney  = floating;
         g_mfeMoney  = floating;
      }
      g_maeMoney = MathMin(g_maeMoney, floating);
      g_mfeMoney = MathMax(g_mfeMoney, floating);
   }
   else if(g_tracking)
      SaveClosedTrackedTrade();

   static datetime lastBar = 0;
   datetime barOpen = iTime(_Symbol, _Period, 0);

   bool isInPosition = PositionSelect(_Symbol);

   // New position -> lock the entry and its stop distance for the target.
   if(isInPosition && !g_wasInPosition)
   {
      double entry = PositionGetDouble(POSITION_PRICE_OPEN);
      double sl    = PositionGetDouble(POSITION_SL);
      if(PositionGetInteger(POSITION_TYPE) == POSITION_TYPE_SELL && sl > entry)
      {
         g_initialEntry = entry;
         g_initialRisk  = sl - entry;
         g_initialSet   = true;
      }
      else
         Print("Invalid SL or entry -> cannot compute risk");
   }
   if(!isInPosition && g_wasInPosition)
   {
      g_initialEntry = 0.0;
      g_initialRisk  = 0.0;
      g_initialSet   = false;
   }
   g_wasInPosition = isInPosition;

   if(barOpen == lastBar) return;
   lastBar = barOpen;

   // Session-clock time of this bar: all time-of-day checks below use it.
   datetime sessionBar = SessionClock(barOpen);

   // ---- session flatten
   if(UseFlattenEnd && !FlattenFallback && IsFlattenTimeEnd(sessionBar))
   {
      CloseAllPositions();
      CancelAllOrders();
      return;
   }
   if(UseFlattenEnd && FlattenFallback)
   {
      datetime barDate  = sessionBar - (sessionBar % 86400);
      datetime prevDate = g_prevBarDate;
      g_prevBarDate = barDate;

      // Previous date ended without a flatten (early close / missing cutoff
      // bar): flatten now, then continue as on any normal session start.
      if(prevDate != 0 && barDate != prevDate && g_lastFlattenDate != prevDate)
      {
         g_lastFlattenDate = prevDate;
         if(PositionsTotal() > 0 || OrdersTotal() > 0)
         {
            CloseAllPositions();
            CancelAllOrders();
         }
      }
      if(IsAtOrAfterFlattenTime(sessionBar))
      {
         if(g_lastFlattenDate != barDate)
         {
            g_lastFlattenDate = barDate;
            CloseAllPositions();
            CancelAllOrders();
         }
         return;   // no new entries after the cutoff
      }
   }

   // ---- open position: only the target check
   if(PositionsTotal() > 0)
   {
      ManageOpenPosition();
      return;
   }

   // ---- entry windows
   if(!IsTradeWindow(sessionBar))
   {
      CancelOldSellLimits();
      return;
   }

   // ---- red candle -> sell limit at its high, replacing the resting order
   double o1 = iOpen(_Symbol, _Period, 1);
   double h1 = iHigh(_Symbol, _Period, 1);
   double l1 = iLow(_Symbol, _Period, 1);
   double c1 = iClose(_Symbol, _Period, 1);
   if(c1 >= o1) return;   // green or doji: leave the resting order alone

   CancelOldSellLimits();

   double range = h1 - l1;
   if(range <= 0.0) return;

   double tick = SymbolInfoDouble(_Symbol, SYMBOL_TRADE_TICK_SIZE);
   if(tick <= 0.0) tick = _Point;

   double entry  = NormalizeDouble(h1 + EntryOffsetTicks * tick, _Digits);
   double stop   = NormalizeDouble(entry + range, _Digits);
   double target = entry - RiskReward * range;

   if(!AllowOrderAtMarket && entry <= SymbolInfoDouble(_Symbol, SYMBOL_BID))
   {
      g_skipped++;
      return;
   }
   g_candleRange = range;

   MqlTradeRequest req = {};
   MqlTradeResult  res = {};
   req.action       = TRADE_ACTION_PENDING;
   req.symbol       = _Symbol;
   req.volume       = Lots;
   req.type         = ORDER_TYPE_SELL_LIMIT;
   req.price        = entry;
   req.sl           = stop;
   if(ExitMode == EXIT_RESTING_TP)
      req.tp        = NormalizeDouble(MathFloor(target / tick + 1e-9) * tick, _Digits);
   req.deviation    = Slippage;
   req.type_filling = ORDER_FILLING_RETURN;

   if(!OrderSend(req, res) || (res.retcode != TRADE_RETCODE_DONE && res.retcode != TRADE_RETCODE_PLACED))
      g_rejected++;
   else
      g_placed++;
}
